class DoorLockRando(Toggle):
    """If enabled, certain door locks (beam-colored doors, blast shields)
    are shuffled among a vetted pool of lock types, instead of each door
    keeping its vanilla lock."""

    display_name = "Door Lock Randomization"


class NormalSaveStationDoors(DefaultOnToggle):
    """If enabled, door lock randomization never puts a restrictive lock on
    a room containing a Save Station: every door of such a room -- and the
    matching face on the far side, which is the one you shoot to get in --
    is forced to a Normal Door (opens with any beam).

    On by default so a save station is always reachable with whatever beam
    you have. Because both faces of a physical door must agree, this also
    makes the neighbouring room's side of that door normal.

    Note this can also *remove* a lock the vanilla game had: a few save
    rooms ship with a Missile Blast Shield or Dark Door, and those are
    normalized too rather than merely left un-randomized.

    No effect unless `door_lock_rando` is on.
    """

    display_name = "Normal Save Station Doors"


class ElevatorRando(Toggle):
    """If enabled, elevators are shuffled into new two-way connections
    (every region reachable via vanilla elevators stays reachable, but not
    necessarily through the same elevator), instead of vanilla
    connections. The one-way trip into Sky Temple and the intra-region
    Aerie elevator are never shuffled."""

    display_name = "Elevator Randomization"


class PortalRando(Toggle):
    """If enabled, the Light/Dark Aether portals (the fixed rift-travel
    pairs in Temple Grounds/Sky Temple Grounds, Agon Wastes/Dark Agon
    Wastes, Torvus Bog/Dark Torvus Bog, and Sanctuary Fortress/Ing Hive) are
    shuffled into new connections, within each light/dark region pair, and
    made two-way (every portal, including the vanilla one-way arrival-only
    ones, can be used in both directions -- open-prime-rando physically
    adds the missing return portal for those). Every portal keeps its own
    beam-color requirement; only where it leads changes."""

    display_name = "Portal Randomization"


class StartingRoom(Choice):
    """Which pool the starting room is drawn from (see
    ``logic/db_reader.py``'s ``GameDatabase.starting_location_candidates``
    for exactly what qualifies -- randovania's own
    ``valid_starting_location`` DB flag).

    Vanilla: always Temple Grounds/Landing Site, matching every seed
    generated before this option existed.
    Save Stations: one of the 18 save-station rooms across the whole game
    (9 in the 5 light regions, 9 in the 5 dark regions).
    Anywhere: one of 272 rooms -- every room randovania's DB considers a
    valid starting location (162 light / 110 dark), including e.g. boss
    arenas and rooms only normally reached via a one-way drop.

    A dark-world start (possible under either non-vanilla pool, unless
    ``starting_room_light_world_only`` is also enabled) means taking Dark
    Aether damage every second from the moment the game begins, until a
    suit or a safe zone is reached -- expect an immediately dangerous
    opening on some seeds.

    ``warp_to_start`` (see below) always returns to whichever room this
    picks; the decline-a-save warp itself only exists in the 18 save-station
    rooms (``can_warp_to_start``), regardless of which pool the actual
    start came from."""

    display_name = "Starting Room"
    option_vanilla = 0
    option_save_stations = 1
    option_anywhere = 2
    default = 0


class StartingRoomLightWorldOnly(Toggle):
    """If enabled, drops every dark-region room (Dark Agon Wastes, Dark
    Torvus Bog, Ing Hive, Sky Temple, Sky Temple Grounds) from whichever
    pool ``starting_room`` selects, guaranteeing a light-world (no Dark
    Aether damage) start. No effect when ``starting_room`` is left at
    Vanilla -- Landing Site is already a light-world room."""

    display_name = "Starting Room: Light World Only"


class TranslatorGateRando(Choice):
    """How each of the 17 translator gates' required color is chosen,
    matching randovania's own translator gate presets.

    Vanilla: every gate requires its vanilla translator color.
    Random: every gate independently requires a random one of the four
    translator colors (Violet/Amber/Emerald/Cobalt).
    Random (Unlocked): like Random, but each gate may also independently
    come up "Unlocked" -- open with just Scan Visor, no translator
    required at all."""

    display_name = "Translator Gate Randomization"
    option_vanilla = 0
    option_full_random = 1
    option_full_random_unlocked = 2
    default = 0


