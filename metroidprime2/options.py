class TrickLevel(Choice):
    """The default difficulty of tricks logic is allowed to require,
    applied to every trick that is left at "Use global setting" in its own
    per-trick option below. Disabled means no tricks are ever required."""

    display_name = "Trick Level"
    option_disabled = 0
    option_beginner = 1
    option_intermediate = 2
    option_advanced = 3
    option_expert = 4
    option_ludicrous = 5
    default = 0


class DamageStrictness(Choice):
    """How strictly damage requirements are calculated. Higher multipliers
    make logic assume incoming damage is larger (and thus require more
    energy tanks / better damage reduction before crossing a damaging
    area), matching randovania's "strict"/"medium"/"lenient" presets."""

    display_name = "Damage Strictness"
    option_strict = 0
    option_medium = 1
    option_lenient = 2
    default = 1


class EnergyPerTank(Range):
    """How much energy (health) each Energy Tank is worth."""

    display_name = "Energy Per Tank"
    range_start = 50
    range_end = 500
    default = 100


class DarkAetherDamage(Range):
    """Damage per second taken while in a dark world without appropriate
    suit protection, in TENTHS of a point per second (e.g. 60 == 6.0
    damage/second). ``Range`` is integer-only, so this and
    ``DarkSuitDamage`` are expressed in tenths rather than whole points --
    that's the only way to represent randovania's fractional Dark Suit
    default (1.2) exactly. Convert back to real damage/second units with
    ``dark_damage_per_second()`` below before using the value; never read
    ``.value`` directly for a damage calculation. The default of 60 (6.0
    damage/second) matches randovania's ``varia_suit_damage: 6.0``."""

    display_name = "Dark Aether Damage (tenths/second)"
    range_start = 10
    range_end = 600
    default = 60


class DarkSuitDamage(Range):
    """Damage per second taken while in a dark world with the Dark Suit
    (but not the Light Suit), in TENTHS of a point per second -- see
    ``DarkAetherDamage``'s docstring for why. The default of 12 (1.2
    damage/second) matches randovania's starter preset (``dark_suit_damage:
    1.2``) exactly; a plain integer ``Range`` in whole damage/second units
    could only default to 1 (~17% more permissive than randovania -- logic
    would assume less dark-aether damage than it should, an out-of-logic
    death risk) or 2 (stricter, but not what randovania actually uses)."""

    display_name = "Dark Suit Damage (tenths/second)"
    range_start = 0
    range_end = 600
    default = 12


