class DisplayNonLocalItems(Choice):
    """How items belonging to other worlds are displayed in-game.

    None: only this world's own items get matching in-game models; every
    other item shows as a generic Energy Transfer Module.
    Match Game: items belonging to another Metroid Prime 2: Echoes player
    also get a matching model, and so do conceptually-equivalent items
    from MultiWorldGG's other Metroid games (Metroid Prime, Metroid: Zero
    Mission, Metroid Fusion, Super Metroid) -- e.g. a Metroid Prime Energy
    Tank or a Super Metroid Missile shows up as this game's own Energy
    Tank/Missile Expansion model (see ``patch_data.py``'s
    ``_CROSS_GAME_ITEM_NAMES``). A handful of these cross-game matches
    (and the Metroid Prime Missile Expansion reskin,
    ``_CROSS_GAME_MODEL_OVERRIDES``) are experimental: they resolve to a
    model this world has never independently verified is safe to place
    outside its own default spot, the same category of open-prime-rando
    defect that made the "Varia Suit" model (never matched, on any game)
    crash the game elsewhere. Anything without a curated match (or from a
    game not in that list) still falls back to the generic model."""

    display_name = "Display Non-Local Items"
    option_none = 0
    option_match_game = 1
    default = 1


class UnvisitedRoomNames(DefaultOnToggle):
    """If enabled, the map shows room names for rooms that have not been
    visited yet."""

    display_name = "Unvisited Room Names"


class MapVisibility(Choice):
    """How much of the in-game map is revealed from the start.

    `vanilla`: the map fills in as you explore, and an item's dot appears
    only once its room has been visited or its map station used.

    `full_map`: every room is drawn from the start (rooms still need to be
    visited to show their name/details). Item dots still wait for their
    room to be visited or a map station used -- same as `vanilla`.

    `full_map_and_items`: currently identical to `full_map` for item dots.
    open-prime-rando hardcodes every pickup's map icon to only ever appear
    once its room is visited or a map station used, with no supported way
    to reveal it earlier (PLAN.md section M) -- unlike the Metroid Prime 1
    randomizer, which this option was originally meant to mirror. Kept as
    a distinct choice (rather than merged into `full_map`) so that if
    open-prime-rando ever adds real pre-visit item reveal, this value can
    pick it up without a player-facing option rename.

    These are one setting rather than two toggles because an item dot needs
    its room drawn to be visible at all -- "item dots without the revealed
    map" would be indistinguishable from `vanilla`.
    """

    display_name = "Map Visibility"
    option_vanilla = 0
    option_full_map = 1
    option_full_map_and_items = 2
    default = 0



class RevealMapRemoved(FreeText):
    """Removed: ``reveal_map`` was folded into ``map_visibility`` (PLAN.md
    section M). Present only so an old YAML that still sets it says so.

    Deliberately *not* a plain ``Options.Removed``: that class rejects any
    value once ``FreeText.from_any`` has stringified it (``cls(str(data))``
    -- so YAML's ``false`` arrives as the truthy string ``"False"``), and
    ``reveal_map: false`` is the line 1.0.0's own
    ``example_world_config.yaml`` shipped. Failing generation for every
    YAML copied from it would be noise: ``false`` means exactly what
    ``map_visibility``'s ``vanilla`` default now means, so nothing is lost.
    Only a value that actually asked for a revealed map loses information,
    so only that is an error.
    """

    visibility = Visibility.none
    default = ""

    # Everything YAML/AP can hand over for a "no" answer, lowercased:
    # absent (the "" default), false, 0, none, off.
    _NOTHING_TO_SAY = frozenset({"", "false", "0", "none", "off"})

    def __init__(self, value: str) -> None:
        if str(value).strip().lower() not in self._NOTHING_TO_SAY:
            raise Exception(
                "`reveal_map` has been replaced by `map_visibility`: use "
                "`map_visibility: full_map`, or `full_map_and_items` to also show "
                "every item location on the map. Then delete the `reveal_map` line."
            )
        super().__init__("")


